#!/usr/bin/env bash

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
PY_EXPORTER="$SCRIPT_DIR/2_export_htmls_from_packages.py"
DEFAULT_JOBS=4

usage() {
  cat <<'EOF'
Usage:
  ./scripts/2_read_tw_data_batch_simple.sh \
      <selected_packages.tsv> <package_count> [options]

Arguments:
  selected_packages.tsv  Package list generated by download_hf_files_year.sh.
  package_count          Positive number of packages, or "all".

Options:
  --seed <int>           Random seed when package_count is a number.
  --jobs <int>           Parallel package workers (default: 4).
  --dry-run              Only print selected packages, do not parse.
  --output-root <dir>    HTML output root (default: outputs/final/htmls).
  -h, --help             Show this message.

Example:
  ./scripts/2_read_tw_data_batch_simple.sh \
      data/2015/selected_packages.tsv 100

  ./scripts/2_read_tw_data_batch_simple.sh \
      data/2015/selected_packages.tsv all
EOF
}

if [[ $# -lt 2 || "${1:-}" == "-h" || "${1:-}" == "--help" ]]; then
  usage
  [[ $# -lt 2 ]] && exit 1 || exit 0
fi

SELECTED_TSV_INPUT="$1"
PACKAGE_COUNT="$2"
shift 2

SEED=""
JOBS="$DEFAULT_JOBS"
DRY_RUN=0
OUTPUT_ROOT="$PROJECT_ROOT/outputs/final/htmls"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --seed)
      [[ $# -lt 2 ]] && { echo "--seed requires a value" >&2; exit 1; }
      SEED="$2"
      shift 2
      ;;
    --jobs)
      [[ $# -lt 2 ]] && { echo "--jobs requires a value" >&2; exit 1; }
      JOBS="$2"
      shift 2
      ;;
    --dry-run)
      DRY_RUN=1
      shift
      ;;
    --output-root)
      [[ $# -lt 2 ]] && { echo "--output-root requires a value" >&2; exit 1; }
      OUTPUT_ROOT="$2"
      shift 2
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      echo "Unknown argument: $1" >&2
      usage
      exit 1
      ;;
  esac
done

if [[ ! "$PACKAGE_COUNT" == "all" && ! "$PACKAGE_COUNT" =~ ^[0-9]+$ ]]; then
  echo "package_count must be a positive integer or all" >&2
  exit 1
fi
if [[ "$PACKAGE_COUNT" != "all" && "$PACKAGE_COUNT" -le 0 ]]; then
  echo "package_count must be a positive integer or all" >&2
  exit 1
fi
if [[ -n "$SEED" && ! "$SEED" =~ ^-?[0-9]+$ ]]; then
  echo "--seed must be an integer" >&2
  exit 1
fi
if [[ ! "$JOBS" =~ ^[0-9]+$ ]] || [[ "$JOBS" -le 0 ]]; then
  echo "--jobs must be a positive integer" >&2
  exit 1
fi
if [[ ! -f "$SELECTED_TSV_INPUT" ]]; then
  echo "selected package list not found: $SELECTED_TSV_INPUT" >&2
  exit 1
fi
if [[ ! -f "$PY_EXPORTER" ]]; then
  echo "missing exporter: $PY_EXPORTER" >&2
  exit 1
fi

SELECTED_TSV="$(cd "$(dirname "$SELECTED_TSV_INPUT")" && pwd)/$(basename "$SELECTED_TSV_INPUT")"
OUTPUT_ROOT_ABS="$(mkdir -p "$OUTPUT_ROOT" && cd "$OUTPUT_ROOT" && pwd)"
WORK_DIR="$(mktemp -d "${TMPDIR:-/tmp}/tw_html_batch.XXXXXX")"
cleanup() {
  rm -rf "$WORK_DIR"
}
trap cleanup EXIT

PACKAGE_LIST="$WORK_DIR/packages.tsv"

python3 - "$SELECTED_TSV" "$PACKAGE_COUNT" "$SEED" "$PACKAGE_LIST" <<'PY'
import random
import sys
from pathlib import Path

input_path = Path(sys.argv[1])
count_text = sys.argv[2]
seed_text = sys.argv[3]
output_path = Path(sys.argv[4])

rows = []
seen_paths = set()
for line in input_path.read_text(encoding="utf-8").splitlines():
    line = line.strip()
    if not line:
        continue
    fields = line.split("\t")
    repo_path = fields[-1].strip()
    if not repo_path or repo_path in seen_paths:
        continue
    seen_paths.add(repo_path)
    rows.append(line)

if not rows:
    raise SystemExit("No packages found in selected_packages.tsv")

if count_text == "all":
    selected = rows
else:
    count = int(count_text)
    if count > len(rows):
        raise SystemExit(f"Requested {count} packages, but only {len(rows)} are listed")
    rng = random.Random(int(seed_text)) if seed_text else random.Random()
    selected = rng.sample(rows, count)
    selected.sort()

output_path.write_text("\n".join(selected) + "\n", encoding="utf-8")
print(f"Listed packages: {len(rows)}")
print(f"Selected packages: {len(selected)}")
PY

echo "Selected package list: $PACKAGE_LIST"
sed -n '1,10p' "$PACKAGE_LIST"

if [[ "$DRY_RUN" -eq 1 ]]; then
  echo "Dry-run enabled. No parsing performed."
  exit 0
fi

YEAR="$(basename "$(dirname "$SELECTED_TSV")")"
python3 "$PY_EXPORTER" \
  --package-list "$PACKAGE_LIST" \
  --data-root "$PROJECT_ROOT/data/$YEAR" \
  --output-root "$OUTPUT_ROOT_ABS/$YEAR" \
  --jobs "$JOBS"
